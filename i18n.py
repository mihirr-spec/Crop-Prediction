def translate(key, lang):
    entry = T.get(key)
    if entry is None:
        return key
    return entry.get(lang) or entry["en"]


def crop_name(crop, lang):
    names = CROP_NAMES.get(crop, {})
    return names.get(lang) or names.get("en") or crop


def js_strings(lang):
    data = {k: translate(k, lang) for k in JS_KEYS}
    data["crops"] = {c: crop_name(c, lang) for c in CROP_NAMES}
    return data
